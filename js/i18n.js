let currentLang = 'zh-CN';

export function setLanguage(lang) {
  currentLang = STRINGS[lang] ? lang : 'zh-CN';
}

export function getLanguage() {
  return currentLang;
}

export function t(key, params = {}) {
  const table = STRINGS[currentLang] || STRINGS['zh-CN'];
  let str = table[key] ?? STRINGS.en[key] ?? key;
  Object.entries(params).forEach(([k, v]) => {
    str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  });
  return str;
}

export function randomEncouragement() {
  const i = Math.floor(Math.random() * ENCOURAGE_COUNT);
  return t(`finish.encourage.${i}`);
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    const html = t(key);
    if (el.dataset.i18nHtml === 'true') el.innerHTML = html;
    else el.textContent = html;
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  root.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    el.alt = t(el.dataset.i18nAlt);
  });
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.content = t('meta.description');
  document.title = t('app.name');
}
